def read_words():
    words = {}
    with LEXICON.open(encoding="utf-8-sig", newline="") as handle:
        rows = csv.reader(handle, strict=True)
        try:
            if next(rows, None) != ["text", "reading", "weight"]:
                raise ValueError("expected text,reading,weight header")
            for row in rows:
                if not row:
                    continue
                if len(row) != 3 or not row[0].strip() or row[0].splitlines() != [row[0]]:
                    raise ValueError("expected text,reading,weight")
                words.setdefault(row[0], None)
        except (csv.Error, ValueError) as error:
            raise ValueError(f"{LEXICON}:{rows.line_num}: {error}") from error
    if not words:
        raise ValueError(f"No words found in {LEXICON}")
    return list(words)


def verify_lexicon(state_path, corpus, words):
    digest = hashlib.sha256()
    for word in words:
        digest.update(word.encode("utf-8") + b"\n")
    state = {
        "format": "plain-dialogue-v1",
        "word_count": len(words),
        "words_sha256": digest.hexdigest(),
    }
    if state_path.is_file():
        if json.loads(state_path.read_text(encoding="utf-8")) != state:
            raise ValueError("The dialogue format or lexicon changed. Use a new --output directory.")
        return
    if corpus.exists() and corpus.stat().st_size:
        raise ValueError("Existing dialogues have no lexicon checkpoint. Use a new --output directory.")
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=state_path.parent, delete=False,
    ) as handle:
        temporary = Path(handle.name)
        try:
            handle.write(json.dumps(state) + "\n")
            handle.flush()
            os.fsync(handle.fileno())
            handle.close()
            temporary.replace(state_path)
        finally:
            temporary.unlink(missing_ok=True)


def validate_dialogue(messages, word):
    if not MIN_MESSAGES <= len(messages) <= MAX_MESSAGES:
        raise ValueError(f"expected {MIN_MESSAGES}–{MAX_MESSAGES} message lines, got {len(messages)}")
    for message in messages:
        if not message:
            raise ValueError("unexpected blank line inside a dialogue")
        if MESSAGE_LABEL.match(message) or message in ("[", "]", "{", "}"):
            raise ValueError("expected bare message text without a speaker, time, or markup")
    if not any(word in message for message in messages):
        raise ValueError("the target word is missing from the message text")


def parse_dialogue(stdout, word):
    messages = [line.strip() for line in stdout.splitlines() if line.strip()]
    if len(messages) >= 2 and TEXT_FENCE.fullmatch(messages[0]) and messages[-1] == "```":
        messages = messages[1:-1]
    labelled = [SPEAKER_PREFIX.fullmatch(message) for message in messages]
    if labelled and all(labelled) and len({match[1] for match in labelled}) >= 2:
        messages = [match[2] for match in labelled]
    validate_dialogue(messages, word)
    return messages


def read_checkpoint(corpus, words):
    completed, last_complete = 0, 0
    lines = []
    with corpus.open("a+b") as handle:
        handle.seek(0)
        for line in handle:
            if line != b"\n":
                lines.append(line)
                continue
            try:
                if completed >= len(words):
                    raise ValueError("more dialogues than lexicon words")
                messages = [line.decode("utf-8").strip() for line in lines]
                validate_dialogue(messages, words[completed])
            except ValueError as error:
                raise ValueError(f"{corpus}: dialogue {completed + 1}: {error}") from error
            completed += 1
            last_complete = handle.tell()
            lines.clear()
        if lines:
            handle.truncate(last_complete)
            handle.flush()
            os.fsync(handle.fileno())
            print(f"Removed an incomplete final dialogue from {corpus}.", file=sys.stderr)
    return completed


